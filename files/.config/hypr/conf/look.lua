-- Gaps, borders, rounding, blur, animations: the hand-written defaults.
-- Anything changed in the settings UI (state/settings.json) is applied after
-- this file and wins; its reset button brings these values back.
-- Refer to https://wiki.hypr.land/Configuring/Basics/Variables/
local C = require("lib.palette")

hl.config({
    general = {
        gaps_in  = 5,
        gaps_out = 20,

        border_size = 2,

        col = {
            active_border = {
                colors = { "rgba(" .. C.primary .. "ee)", "rgba(" .. C.tertiary .. "ee)" },
                angle = 45,
            },
            inactive_border = "rgba(" .. C.outline .. "66)",
        },

        -- Set to true to enable resizing windows by clicking and dragging on borders and gaps
        resize_on_border = false,

        -- Please see https://wiki.hypr.land/Configuring/Advanced-and-Cool/Tearing/ before you turn this on
        allow_tearing = false,

        layout = "dwindle",
    },

    decoration = {
        rounding       = 10,
        rounding_power = 2,

        -- Change transparency of focused and unfocused windows
        active_opacity   = 1.0,
        inactive_opacity = 1.0,

        shadow = {
            enabled      = true,
            range        = 4,
            render_power = 3,
            color        = 0xee1a1a1a,
        },

        blur = {
            enabled   = true,
            size      = 3,
            passes    = 1,
            vibrancy  = 0.1696,
        },
    },

    animations = {
        enabled = true,
    },

    -- See https://wiki.hypr.land/Configuring/Layouts/ for the layout sections
    dwindle = {
        preserve_split = true, -- You probably want this
    },
    master = {
        new_status = "master",
    },
    scrolling = {
        fullscreen_on_one_column = true,
    },

    misc = {
        force_default_wallpaper = 0,    -- Set to 0 or 1 to disable the anime mascot wallpapers
        disable_hyprland_logo   = true, -- If true disables the random hyprland logo / anime girl background. :(
        -- If the lock screen (the shell's) ever dies while locked, let a
        -- new one take over (SUPER+L, or hypridle) instead of staying stuck.
        allow_session_lock_restore = true,
        -- Once hypridle has turned the displays off, a key or the mouse brings
        -- them back. Hyprland's own default is neither, which leaves only
        -- hypridle's on-resume - and nothing if that listener is gone.
        mouse_move_enables_dpms = true,
        key_press_enables_dpms  = true,
        -- The first frames, before the wallpaper daemon has drawn: the palette's
        -- surface colour rather than black.
        background_color = "rgb(" .. C.surface .. ")",
    },
})

